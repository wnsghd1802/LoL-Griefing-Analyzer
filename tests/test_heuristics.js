const assert = require('node:assert/strict');
const { analyzeTimeline, classifyOCR } = require('../heuristics.js');
assert.deepEqual(classifyOCR('다음 용 먹자'), []);
assert.deepEqual(classifyOCR('오픈함'), ['게임 포기·방해 선언 후보']);
assert.deepEqual(classifyOCR('씨발'), ['공격적 표현 후보']);
assert.throws(()=>analyzeTimeline({}),/info.frames/);
const clean={info:{frames:[]}};
for(let m=0;m<=12;m++) clean.info.frames.push({timestamp:m*60000,participantFrames:{'1':{participantId:1,minionsKilled:m*5,position:{x:1000+250*m,y:2000+300*m}},'2':{participantId:2,minionsKilled:m*1,position:{x:1000+400*m,y:2000+280*m}}},events:[]});
assert.equal(analyzeTimeline(clean).findings.length,0);
assert.equal(analyzeTimeline(clean,{jungleId:'2',csRate:5}).findings.length,0);
const altered=structuredClone(clean);
for(let m=6;m<=12;m++)altered.info.frames[m].participantFrames['2'].minionsKilled= m*7-30;
for(let m=4;m<=8;m++)altered.info.frames[m].participantFrames['1'].position={x:4500,y:4500};
for(const m of [6,8,10])altered.info.frames[m].events.push({type:'CHAMPION_KILL',victimId:2,timestamp:m*60000});
const out=analyzeTimeline(altered,{jungleId:'2',csRate:5});
assert.ok(out.findings.some(f=>f.rule==='일반 미니언 집중'));
assert.ok(out.findings.some(f=>f.rule==='위치 변화 감소'));
assert.ok(out.findings.some(f=>f.rule==='사망 집중'));
assert.ok(out.findings.every(f=>f.status==='검토 필요'));
